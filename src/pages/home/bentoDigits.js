export function hasDigitGlyph(digit) {
    return Object.prototype.hasOwnProperty.call(DIGITS, digit)
}

//Inline svg string, filled with currentColor; null for a digit without a glyph
export function digitSvg(digit) {
    let glyph = DIGITS[digit]
    if (!glyph) return null
    let fillRule = glyph.isEvenOdd ? ' fill-rule="evenodd" clip-rule="evenodd"' : ''
    return `<svg viewBox="${glyph.viewBox}" preserveAspectRatio="none" fill="none" aria-hidden="true" xmlns="http://www.w3.org/2000/svg">` +
        `<path${fillRule} d="${glyph.path}" fill="currentColor"/></svg>`
}

//Glyph box as % of the card — { left, top, width, height } strings
export function digitPlacement(digit) {
    let glyph = DIGITS[digit]
    if (!glyph) return null
    let percentOfWidth = (value) => `${(value / DESIGN_CARD_WIDTH) * 100}%`
    let percentOfHeight = (value) => `${(value / DESIGN_CARD_HEIGHT) * 100}%`
    return {
        left: percentOfWidth(glyph.left),
        top: percentOfHeight(glyph.top),
        width: percentOfWidth(glyph.width),
        height: percentOfHeight(glyph.height),
    }
}
